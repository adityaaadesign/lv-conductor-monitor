// Builds the dashboard as plain files for Vercel (folder dist/). Nothing is compiled:
// frontend/ and shared/ are copied, plus the modules and config the in-browser DEMO needs
// (server/demo-assets.js), and config.js is written with the backend address.
//
//   API_BASE_URL=https://lv-monitor-api.<your-subdomain>.workers.dev node tools/build-frontend.js
//
// On Vercel, set API_BASE_URL in Project → Settings → Environment Variables.
// Not needed on the laptop: there the server serves the dashboard itself.

import { cpSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BROWSER_MODULES, demoDataFiles } from '../server/demo-assets.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'dist');
const apiBase = (process.env.API_BASE_URL || '').trim().replace(/\/+$/, '');

if (!/^https?:\/\/[^/\s]+$/.test(apiBase)) {
  console.error('API_BASE_URL is missing or wrong. Set it to the backend address only, for example');
  console.error('  https://lv-monitor-api.<your-subdomain>.workers.dev   (no /api/v1, no trailing slash)');
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
cpSync(path.join(root, 'frontend'), out, { recursive: true });
cpSync(path.join(root, 'shared'), path.join(out, 'shared'), { recursive: true });
// In-browser DEMO: only the listed modules and the non-secret config (server/demo-assets.js).
for (const rel of BROWSER_MODULES) cpSync(path.join(root, rel), path.join(out, rel));
mkdirSync(path.join(out, 'demo'), { recursive: true });
for (const [name, data] of Object.entries(demoDataFiles(root))) writeFileSync(path.join(out, 'demo', name), JSON.stringify(data));
writeFileSync(path.join(out, 'config.js'),
  `// Generated by tools/build-frontend.js – address of the monitoring server.\nwindow.LV_API_BASE = ${JSON.stringify(apiBase)};\n`);
console.log(`Dashboard built in dist/ – it will read data from ${apiBase}`);
